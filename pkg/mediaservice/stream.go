package mediaservice

import (
	"io"

	"mediaservice/internal/media"
)

// uploadChunkSize - размер порции, которой библиотека читает reader.
//
// Значение своё, с размером gRPC-сообщения не связано: копирование идёт
// внутри процесса, ограничений транспорта здесь нет. Мегабайт - компромисс
// между числом вызовов и объёмом, который придётся перечитать, если
// загрузка оборвётся.
const uploadChunkSize = 1 << 20

// clientBoundStream - поток из DownloadStream, привязанный к жизни клиента.
//
// Зачем нужен. Метод возвращает io.ReadCloser и отпускает блокировку клиента:
// держать её всё время чтения нельзя, иначе один медленный читатель подвесил
// бы Close для всех. Значит клиент может быть закрыт, пока поток ещё читают.
//
// Без обёртки такое чтение сегодня продолжало бы работать - но лишь потому,
// что Close у адаптера MinIO ничего не делает и возвращает nil. Это
// совпадение реализации, а не свойство контракта: как только адаптер начнёт
// освобождать ресурсы, чтение после Close начнёт падать ошибкой уровня
// драйвера, из которой вызывающий не поймёт, что произошло.
//
// Обёртка превращает это в предсказуемое поведение: чтение после Close даёт
// ErrClosed, ту же ошибку, что и любой метод клиента.
//
// Close у самой обёртки работает всегда, в том числе после закрытия клиента:
// соединение с хранилищем нужно освободить в любом случае, и запрет на это
// превратил бы обёртку из страховки в утечку.
type clientBoundStream struct {
	rc     io.ReadCloser
	client *Client
}

// Read отдаёт ErrClosed, если клиент закрыт, и не трогает нижележащий поток.
//
// Проверка идёт на каждом Read, а не один раз при создании: клиент может
// закрыться в любой момент между чтениями, и смысл обёртки именно в том,
// чтобы это заметить.
func (s *clientBoundStream) Read(p []byte) (int, error) {
	if s.client.isClosed() {
		return 0, ErrClosed
	}
	return s.rc.Read(p)
}

// Close закрывает нижележащий поток. Идемпотентность определяется
// нижележащей реализацией, повторный вызов библиотека не перехватывает.
func (s *clientBoundStream) Close() error {
	return s.rc.Close()
}

// readerChunks превращает io.Reader в функцию, которую ждёт ядро.
//
// Ядро читает тело загрузки повторными вызовами до io.EOF. Такой контракт
// достался ему от gRPC-стрима, где следующего куска приходится ждать;
// для io.Reader это обычный цикл чтения в буфер.
//
// Буфер один на всю загрузку и переиспользуется. Так можно, потому что ядро
// разбирается с куском полностью до следующего вызова: пишет во временный
// файл и досчитывает хеш синхронно, ссылку на срез не сохраняет. Замена этой
// части ядра на асинхронную сломала бы предположение молча, поэтому оно
// записано здесь.
func readerChunks(r io.Reader) media.ChunkReceiver {
	buf := make([]byte, uploadChunkSize)
	var sticky error

	return func() ([]byte, error) {
		// Ошибка запоминается и повторяется при каждом следующем вызове.
		// io.Reader не обязан отдавать io.EOF повторно, а ядро вправе
		// спросить ещё раз - без этого загрузка могла бы не завершиться.
		if sticky != nil {
			return nil, sticky
		}

		n, err := r.Read(buf)
		if err != nil {
			sticky = err
		}

		// Данные важнее ошибки: io.Reader вправе вернуть прочитанные байты
		// вместе с io.EOF, и потерять их нельзя. Ошибка доедет следующим
		// вызовом.
		if n > 0 {
			return buf[:n], nil
		}
		if err != nil {
			return nil, err
		}

		// (0, nil) по контракту io.Reader означает "ничего не произошло".
		// Отдаём пустой кусок: ядро считает подряд идущие пустые куски
		// и оборвёт загрузку, если reader зациклится.
		return nil, nil
	}
}
