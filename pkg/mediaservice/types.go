package mediaservice

import (
	"time"

	"github.com/google/uuid"
)

// Variant определяет тип производного (оптимизированного) файла, созданного из оригинала.
// Используется в методах GetDownloadURL и DownloadStream для запроса конкретной версии файла.
type Variant string

const (
	VariantOriginal Variant = "original" // Исходный загруженный файл.
	VariantThumb    Variant = "thumb"    // Статичное превью (кадр для видео, waveform для аудио, уменьшенное изображение).
	VariantPreview  Variant = "preview"  // Зарезервировано, в текущей версии не создаётся.
	VariantR720     Variant = "r_720"    // Транскодированная версия видео в разрешении 720p.
	VariantR360     Variant = "r_360"    // Зарезервировано, в текущей версии не создаётся.
)

// Status отражает текущий этап жизненного цикла медиаобъекта.
// Стандартный поток: Stored -> Processing -> Ready (или Failed).
// Статус Deleting является внутренним переходным состоянием для согласованного удаления.
type Status string

const (
	StatusStored     Status = "stored"     // Файл загружен, ожидает постановки в очередь обработки.
	StatusProcessing Status = "processing" // Идёт асинхронная генерация превью или транскодирование.
	StatusReady      Status = "ready"      // Оригинальный файл и все запрошенные производные готовы к отдаче.
	StatusFailed     Status = "failed"     // Обработка завершилась с ошибкой (подробности в поле Error).
	StatusDeleting   Status = "deleting"   // Внутренний статус: объект помечен на удаление, идёт очистка хранилища.
)

// Kind определяет класс медиафайла.
// Значение устанавливается автоматически на основе анализа бинарного содержимого (через ffprobe)
// в момент загрузки, а не на основе расширения или заявленного пользователем MIME-типа.
type Kind string

const (
	KindImage Kind = "image"
	KindVideo Kind = "video"
	KindAudio Kind = "audio"
)

// Media - публичная модель медиаобъекта, возвращаемая методами библиотеки.
// Состав полей соответствует message Media из gRPC-контракта.
//
// Внутренние детали реализации (storage_key) наружу не отдаются. Параметры,
// влияющие только на запись (idempotency_key, ttl), живут в UploadParams.
type Media struct {
	ID          uuid.UUID      // Уникальный идентификатор медиаобъекта, генерируется сервером.
	OwnerID     uuid.UUID      // Идентификатор внешнего владельца, которому принадлежит объект.
	Kind        Kind           // Определённый класс файла (image/video/audio).
	MIMEType    string         // Фактический MIME-тип, подтверждённый анализом содержимого.
	SizeBytes   uint64         // Размер оригинального файла в байтах.
	Status      Status         // Текущий статус обработки.
	Metadata    map[string]any // Метаданные, извлечённые ffprobe (duration, width, height, codec и т.д.).
	Derivatives []Derivative   // Список созданных производных файлов. Пуст, если не запрошены или в обработке.
	Error       string         // Описание причины ошибки, если Status == Failed. Пустая строка в остальных случаях.
	CreatedAt   time.Time      // Время создания записи в системе (UTC).
}

// Derivative описывает производный файл, сгенерированный из основного медиаобъекта.
type Derivative struct {
	Variant   Variant // Тип производного файла.
	MIMEType  string  // MIME-тип производного файла (может отличаться от оригинала, напр. image/webp).
	SizeBytes uint64  // Размер производного файла в байтах.
}

// PresignedURL содержит временную ссылку на скачивание медиафайла.
// Ссылка действительна только до момента, указанного в ExpiresAt.
type PresignedURL struct {
	URL       string    // Прямая ссылка на объект в хранилище.
	ExpiresAt time.Time // Момент, после которого ссылка перестанет работать.
}

// UploadParams содержит параметры для инициализации загрузки медиафайла через метод Upload.
// Сами байты передаются отдельным io.Reader, чтобы файл не поднимался в память целиком.
type UploadParams struct {
	OwnerID  uuid.UUID // Владелец, к которому будет привязан объект.
	Filename string    // Исходное имя файла. В ключ хранилища не попадает, используется для определения расширения.
	MIMEType string    // Заявленный клиентом тип. Фактический определяется анализом содержимого.

	// ExpectedSize - заявленный размер файла в байтах. Проверяется на соответствие
	// лимиту до приёма байтов для раннего отказа и экономии ресурсов диска.
	ExpectedSize uint64

	// IdempotencyKey защищает от дублей при повторе запроса: загрузка с тем же
	// ключом от того же владельца вернёт существующий объект вместо создания нового.
	IdempotencyKey string

	// Processing учитывается только при включённой асинхронной обработке.
	// Иначе объект останется в статусе Stored, производные создаваться не будут.
	Processing ProcessingOptions

	// TTL - срок жизни объекта. Ноль означает хранить бессрочно.
	TTL time.Duration
}

// ProcessingOptions содержит флаги для запроса асинхронной обработки
// медиафайла при загрузке (соответствует ProcessingOptions в proto).
type ProcessingOptions struct {
	// MakeThumbnail запрашивает генерацию превью:
	// - для видео: статичный кадр (по умолчанию с 1-й секунды)
	// - для аудио: изображение waveform (звуковая волна)
	// - для изображения: уменьшенная копия по большей стороне
	MakeThumbnail bool

	// Transcode запрашивает асинхронное транскодирование файла.
	// ВАЖНО: в текущей версии (v1) транскодирование выполняется только
	// для видео в единственную рендицию 720p (h264 + aac)
	Transcode bool
}

// ListParams задаёт выборку медиаобъектов одного владельца.
// Пагинация курсорная: PageToken из предыдущего ответа указывает позицию,
// с которой продолжить. В отличие от offset, не сбивается при вставках
// и удалениях между запросами.
type ListParams struct {
	OwnerID   uuid.UUID // Владелец, чьи объекты запрашиваются.
	PageSize  uint32    // Максимальное число объектов в ответе.
	PageToken string    // Позиция для продолжения. Пустая строка означает начало выборки.
}

// ListResult - страница результатов ListByOwner.
type ListResult struct {
	Items         []Media // Объекты текущей страницы.
	NextPageToken string  // Токен следующей страницы. Пустая строка означает, что страниц больше нет.
}
